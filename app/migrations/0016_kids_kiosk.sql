-- What a card reader actually hands over.
--
-- There are two kinds of thing a reader can emit and they are NOT
-- interchangeable:
--
--   the NDEF record — the URL we wrote to the tag, carrying our own opaque
--                     token. Secret, generated by us, revocable.
--   the tag's UID   — a serial number burned in by the chip manufacturer.
--                     NOT secret: it is fixed, often printed on the card, and
--                     trivially cloned onto a blank tag.
--
-- Most inexpensive readers emit the UID by default, so it has to be supported.
-- But it is stored SEPARATELY from the token, and the difference is the whole
-- point: a UID may check a child in and nothing more, while the token is what
-- opens that child's profile on a teacher's phone. Cloning a UID gets you the
-- ability to mark a child present, which is a nuisance. If the UID were the
-- profile key it would get you their address.
ALTER TABLE `kid_cards` ADD `uid` text;

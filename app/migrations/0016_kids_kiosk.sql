-- Unique where present, so one tag cannot be registered to two children — that
-- would make a scan ambiguous and credit the wrong child. Partial, because
-- most cards will have no UID until they are scanned once to learn it.
CREATE UNIQUE INDEX `kid_cards_uid` ON `kid_cards` (`uid`) WHERE `uid` IS NOT NULL;

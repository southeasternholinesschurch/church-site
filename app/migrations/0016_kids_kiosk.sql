-- The check-in kiosk, and what a card reader can emit.
--
-- A SHARED TABLET IN A HALLWAY WITH CHILDREN AROUND IT. Everything here follows
-- from that one fact.
--
-- It must never hold a staff session. A borrowed or stolen tablet carrying one
-- would open every child's address, every guardian's phone number and every
-- allergy note. So the kiosk is a SEPARATE PRINCIPAL with exactly one
-- capability — check a child in — and it is deliberately not a `staff` row with
-- a narrow role, because SessionUser flows into every route in this app and one
-- missed check would hand a hallway tablet everything.
CREATE TABLE `kiosk_devices` (
	`id` integer PRIMARY KEY AUTOINCREMENT NOT NULL,
	-- What it is called on the register screen. "Foyer iPad".
	`name` text NOT NULL,
	-- The pairing secret, held in a cookie on that one tablet. Long, random and
	-- opaque, like a session token — and revocable the same way, because the
	-- realistic failure here is the tablet walking off, not the token leaking.
	`token` text NOT NULL,
	`active` integer DEFAULT 1 NOT NULL,
	-- So a director can tell a tablet that is working from one that has been
	-- unplugged since March. Written on each scan, not each request.
	`last_seen_at` text,
	`revoked_at` text,
	`created_by` text,
	`created_at` text NOT NULL
);
